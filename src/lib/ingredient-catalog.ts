function createIngredient(seed: CatalogSeed): IngredientDefinition {
  const base = archetypes[seed.archetype];
  const mergedProperties = {
    ...base.initialProperties,
    ...seed.properties,
  };
  return {
    id: seed.id,
    name: seed.name,
    englishName: seed.englishName,
    category: seed.category,
    archetype: seed.archetype,
    tagline: seed.tagline,
    description: base.description,
    art: base.art,
    palette: seed.palette,
    initialProperties: mergedProperties,
    baseFlavor: base.baseFlavor,
    appearance: base.appearance,
    keyProperties: [...(seed.keyProperties ?? []), ...base.prepGuide.slice(0, 2).map((item) => item.title)],
    prepGuide: base.prepGuide,
    heatBehavior: base.heatBehavior,
    seasoningStrategy: base.seasoningStrategy,
    commonMistakes: base.commonMistakes,
    safety: base.safety,
    safeCookedness: seed.safeCookedness ?? 60,
    heatSensitivity: base.heatSensitivity,
    browningTendency: base.browningTendency,
    starchiness: seed.starchiness ?? (seed.archetype === "root" ? 0.5 : 0.05),
    protein: seed.protein ?? 0.1,
    fat: seed.fat ?? 0.03,
    sensitivities: base.sensitivities,
  };
}

export const additionalIngredients: IngredientDefinition[] =
  seeds.map(createIngredient);
