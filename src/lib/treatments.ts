export function treatmentsForIngredient(ingredientId: string): TreatmentDefinition[] {
  const ingredient = getIngredient(ingredientId);
  return treatments.filter(
    (treatment) =>
      treatment.category === "universal" ||
      treatment.ingredientIds?.includes(ingredientId) ||
      treatment.archetypes?.includes(ingredient.archetype),
  );
}

export function treatmentGroupsForIngredient(ingredientId: string) {
  const available = treatmentsForIngredient(ingredientId);
  return {
    mechanical: available.filter((item) => item.category === "mechanical"),
    "water-salt": available.filter((item) => item.category === "water-salt"),
    biological: available.filter((item) => item.category === "biological"),
    universal: available.filter((item) => item.category === "universal"),
  };
}

